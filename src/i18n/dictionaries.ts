export const dictionaries: Record<Locale, Record<TranslationKey, string>> = { en, uk };

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (LOCALES as readonly string[]).includes(value);
}

export function translate(
  locale: Locale,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  let text: string = dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export type T = (key: TranslationKey, vars?: Record<string, string | number>) => string;

export function makeT(locale: Locale): T {
  return (key, vars) => translate(locale, key, vars);
}
